import assert from 'node:assert/strict';
import { readBoundedModelResponse, MAX_LOCAL_MODEL_RESPONSE_BYTES } from '../src/agent/localModelClient.js';
import { createDerivedProductCache, DERIVED_CACHE_LIMITS } from '../src/derived/derivedProductCache.js';
const limit=MAX_LOCAL_MODEL_RESPONSE_BYTES;
const chunk=new Uint8Array(limit).fill(97);let cancelled=false;
const response=new Response(new ReadableStream({start(c){c.enqueue(chunk);c.enqueue(new Uint8Array([97]));},cancel(){cancelled=true;}}));
await assert.rejects(readBoundedModelResponse(response),e=>e.classification==='response_resource_limit');assert.equal(cancelled,true);
assert.equal((await readBoundedModelResponse(new Response('a'.repeat(limit)))).length,limit);
assert.equal(await readBoundedModelResponse(new Response('é😀')), 'é😀');
await assert.rejects(readBoundedModelResponse(new Response('small',{headers:{'content-length':String(limit+1)}})),/8 MiB/);
const cache=createDerivedProductCache();const rows=[];cache.activateGraph(1,rows);
const huge='x'.repeat(DERIVED_CACHE_LIMITS.textBytes/2+1);
assert.equal(cache.getOrCompute('export',{},()=>huge),huge,'oversized exact export still returned');
assert.equal(cache.getSnapshot().entryCount,0,'oversized text not retained');
for(let i=0;i<100;i++)cache.getOrCompute('export',{i},()=>String(i));
assert.equal(cache.getSnapshot().entryCount,32);
assert.ok(cache.getSnapshot().retainedTextBytes<=DERIVED_CACHE_LIMITS.textBytes);
cache.activateGraph(2,[]);assert.equal(cache.getSnapshot().retainedTextBytes,0);
console.log('Scope 6B response byte admission/cancellation, UTF-8 and exact export cache budgets passed.');
