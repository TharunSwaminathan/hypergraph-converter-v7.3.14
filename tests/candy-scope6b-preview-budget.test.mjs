import assert from 'node:assert/strict';
import { prepareBoundedPreview } from '../src/visualization/previewRenderBudget.js';
import { buildPreviewTopology } from '../src/visualization/hypergraphLayout.js';
import { expH2V, buildH2V } from '../src/utils/mappings.js';
import { buildMappingPresentation } from '../src/derived/mappingPresentation.js';
const huge=[{id:'huge',vertices:Array.from({length:1_000_000},(_,i)=>`v${i}`)}];
const visual=prepareBoundedPreview(huge,10000);
assert.equal(visual.renderedVertices,1000);assert.equal(visual.renderedIncidences,1000);
assert.equal(visual.totalIncidences,1_000_000);assert.equal(visual.complete,false);
assert.equal(buildPreviewTopology(visual.hyperedges).vertices.length,1000);
assert.equal(huge[0].vertices.length,1_000_000,'bounding never mutates source');
const exported=expH2V(buildH2V(huge));assert.ok(exported.endsWith('v999999'));
const mapping=buildMappingPresentation('h2v',buildH2V(huge));
assert.equal(mapping.complete,false);assert.equal(mapping.rows[0][4],'1000000');
assert.ok(mapping.rows[0][2].length<600);assert.match(mapping.rows[0][2],/export for all/);
const many=Array.from({length:10000},(_,i)=>({id:`e${i}`,vertices:[`v${i}`]}));
assert.equal(prepareBoundedPreview(many,10000).renderedHyperedges,200);
assert.equal(prepareBoundedPreview(many,Infinity).renderedHyperedges,50);
assert.equal(prepareBoundedPreview(many,NaN).renderedHyperedges,50);
assert.equal(prepareBoundedPreview([{id:'small',vertices:['a','b']}],50).complete,true);
console.log('Scope 6B million-membership display budgets and exact full export passed.');
