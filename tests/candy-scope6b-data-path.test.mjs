import assert from 'node:assert/strict';
import { createGraphState, commitGraphState } from '../src/graph/graphState.js';
import { graphFingerprint, graphDerivationMetrics } from '../src/graph/graphFingerprint.js';
import { graphCounts, previewGraphMutation } from '../src/graph/graphMutationPreview.js';
import { createGraphHistoryEvent, appendGraphHistory, graphHistoryUsage } from '../src/graph/graphHistory.js';
import { createDerivedProductCache } from '../src/derived/derivedProductCache.js';
import { buildGraphMutationPlannerContext } from '../src/agent/prompts/graphMutationPlannerPrompt.js';
import { buildAssistantApplicationSnapshot } from '../src/agent/assistantContextSnapshot.js';
import { createMutationPlan } from '../src/graph/graphMutationValidator.js';
import { createPendingHypergraphUpdateController } from '../src/graph/pendingHypergraphUpdate.js';

const raw=[{id:'e0',vertices:['a','b'],attributes:{nested:{value:1}}}];
const state=createGraphState(raw);
raw[0].vertices.push('external');raw[0].attributes.nested.value=2;
assert.deepEqual(state.hyperedges[0].vertices,['a','b']);
assert.equal(state.hyperedges[0].attributes.nested.value,1);
assert.throws(()=>state.hyperedges[0].vertices.push('mutated'),TypeError);
assert.throws(()=>{state.hyperedges[0].attributes.nested.value=3;},TypeError);
const start=graphDerivationMetrics();
for(let i=0;i<100;i++){graphFingerprint(state.hyperedges);graphCounts(state.hyperedges);}
assert.equal(graphDerivationMetrics().canonicalizations,start.canonicalizations);
const mutable=[{id:'e',vertices:['a']}];const before=graphFingerprint(mutable);mutable[0].vertices.push('b');
assert.notEqual(graphFingerprint(mutable),before,'mutable inputs never qualify for cached identity');
const next=commitGraphState(state,[{id:'e0',vertices:['b','c']}]);
assert.equal(next.graphVersion,state.graphVersion+1);
assert.deepEqual(graphCounts(next.hyperedges),{hyperedges:1,vertices:2,incidences:2});
assert.notEqual(next.graphFingerprint,state.graphFingerprint);
const cache=createDerivedProductCache();let computations=0;
cache.activateGraph(state.graphVersion,state.hyperedges);
assert.equal(cache.getSnapshot().entryCount,0,'no eager representations');
for(let i=0;i<100;i++)cache.getOrCompute('view',{},()=>++computations);
assert.equal(computations,1);
cache.activateGraph(next.graphVersion,next.hyperedges);cache.getOrCompute('view',{},()=>++computations);
assert.equal(computations,2);
assert.equal(cache.setCompleteForGraph(state.graphVersion,state.hyperedges,'late',{},[]),false);
const makeEvent=(a,b)=>createGraphHistoryEvent({graphIdentity:b,beforeHyperedges:a.hyperedges,afterHyperedges:b.hyperedges});
const event=makeEvent(state,next);assert.equal(event.beforeHyperedges,state.hyperedges);assert.equal(event.afterHyperedges,next.hyperedges);
let history=[];for(let i=0;i<10000;i++)history=appendGraphHistory(history,event);
assert.equal(history.length,25);assert.equal(graphHistoryUsage(history).snapshotCount,2);
const bytes=graphHistoryUsage([event]).snapshotBytes;
assert.equal(appendGraphHistory([],event,25,bytes).length,1);
assert.equal(appendGraphHistory([],event,25,bytes-1).length,0);
const undo=createMutationPlan({graphIdentity:next,operations:[{type:'UNDO_LAST_MUTATION'}]});
const restored=previewGraphMutation(next.hyperedges,undo,next,[event]);
assert.equal(restored.ok,true);assert.deepEqual(restored.hyperedges[0].vertices,['a','b']);
const context=buildGraphMutationPlannerContext({hyperedges:next.hyperedges,graphIdentity:next,selectedEntity:{type:'vertex',id:'c'}});
assert.deepEqual(context.selection.selectedVertexIds,['c']);context.entitySamples.vertexIds.push('forged');
assert.equal(buildGraphMutationPlannerContext({hyperedges:next.hyperedges,graphIdentity:next}).entitySamples.vertexIds.includes('forged'),false);
const snapshot=buildAssistantApplicationSnapshot({hasGraph:true,graphId:next.graphId,graphVersion:next.graphVersion,graphType:next.graphType,hyperedgeCount:1,vertexCount:2,incidenceCount:2});
assert.equal(snapshot.graph.version,next.graphVersion);assert.equal(JSON.stringify(snapshot).includes('hyperedgesById'),false);
let dynamic=createGraphState(Array.from({length:257},(_,i)=>({id:`e${i}`,vertices:[`v${i}`]})),{graphType:'DynamicHypergraph'});
const controller=createPendingHypergraphUpdateController({getGraphState:()=>dynamic,commit:()=>assert.fail('No auto Apply')});
await assert.rejects(controller.stage(createMutationPlan({graphIdentity:dynamic,operations:[{type:'REMOVE_HYPEREDGE',hyperedgeId:'e0'}]})),/256 hyperedges/);
dynamic=commitGraphState(dynamic,[{id:'e0',vertices:['a','b']}]);
const pending=(await controller.stage(createMutationPlan({graphIdentity:dynamic,operations:[{type:'REMOVE_HYPEREDGE',hyperedgeId:'e0'}]}))).pendingUpdate;
dynamic=commitGraphState(dynamic,[{id:'e0',vertices:['new']}]);controller.onGraphTransition(dynamic);
assert.equal(controller.getCurrent().status,'STALE');assert.equal(pending.baseGraphRef.graphVersion,dynamic.graphVersion-1);
console.log('Scope 6B immutable ownership, cache invalidation, lazy demand, history budgets/undo, Assistant truth and Dynamic staleness passed.');
