function expectedHelpSpeechAct(text = "") {
  if (isHelpSeekingQuestionText(text)) return "help_seeking_question";
  if (/^\s*(?:how|why)\b/i.test(text)) return "explanation_question";
  if (/^\s*show\b/i.test(text)) return "imperative_request";
  return "informational_question";
}

function expectedLegacySpeechAct(text = "", intent = "") {
  if (intent === "correction") return "correction";
  if (/^\s*(?:stop|cancel|abort)\b/i.test(text)) return "cancellation";
  return "imperative_request";
}

