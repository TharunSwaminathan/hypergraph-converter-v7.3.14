function legacyActionCatalogEntries() {
  return ACTION_INTENT_REGISTRY
    .filter(action => action.visibility === ACTION_INTENT_VISIBILITY.PUBLIC)
    .map(action => ({
      id: action.id,
      category: action.category,
      domain: "legacy_action",
      intent: action.intent,
      typedKind: TYPED_KINDS.LEGACY_ACTION_INTENT,
      operationTypes: [action.intent],
      title: action.title,
      summary: `${action.summary} To learn about this command, ask “How do I ${action.aliases?.[0] ?? action.title.toLowerCase()}?” To execute it, use a direct request such as “${action.examples?.[0] ?? action.title}.”`,
      patterns: [...(action.patterns ?? []), ...(action.aliases ?? [])],
      examples: (action.examples ?? []).map(text => legacyExample(text, action.intent, {
        expectedSideEffect: action.sideEffect,
        expectedSpeechAct: expectedLegacySpeechAct(text, action.intent),
      })),
      requiredContext: action.requiredContext,
      sideEffect: action.sideEffect,
      confirmation: action.confirmation,
      reversible: !action.destructive,
      destructive: action.destructive,
      worksOffline: true,
      modelPolicy: action.modelPolicy,
      ambiguityNotes: action.destructive
        ? ["This action changes assistant workspace state. Ask as a How-do-I question to learn about it without executing it."]
        : ["Help-seeking forms are read-only; direct requests use the existing deterministic handler."],
      identifierNotes: [],
      relatedCommandIds: action.relatedCommandIds,
      availability: action.availability,
      sinceVersion: CATALOG_CURRENT_VERSION,
    }));
}

