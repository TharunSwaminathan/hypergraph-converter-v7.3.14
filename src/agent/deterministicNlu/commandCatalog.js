export function getCatalogEntry(id) {
  return COMMAND_CATALOG.find(entry => entry.id === id) ?? null;
}

export function catalogEntriesByCategory(category) {
  return COMMAND_CATALOG.filter(entry => entry.category === category);
}

export function getQuickStartEntries() {
  return QUICK_START_COMMAND_IDS.map(getCatalogEntry).filter(Boolean);
}

export function allCatalogExamples({ includePanelOnly = false } = {}) {
  return COMMAND_CATALOG
    .filter(entry => includePanelOnly || entry.availability !== COMMAND_AVAILABILITY.PANEL_ONLY)
    .flatMap(entry => (entry.examples ?? []).map(example => ({ entry, example })));
}

export function exportPreviewLabels() {
  return Object.values(EXPORT_PREVIEWS).map(item => item.label);
}
